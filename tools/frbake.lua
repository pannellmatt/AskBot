-- Bakes ForeverRecipes' recipe data into AskBot's RecipeData.lua.
-- ForeverRecipes keeps its tables private (addon namespace), so AskBot can't read them in game.
-- Re-run when ForeverRecipes updates:
--   luajit tools\frbake.lua "<_forever_>\Interface\AddOns\ForeverRecipes" RecipeData.lua
-- ForeverRecipes is GPL-3.0 (Ismail and contributors; Classic reference data from CMaNGOS
-- Classic DB, GPL-3.0), like AskBot.
local src, out = arg[1], arg[2] or "RecipeData.lua"
assert(src, "usage: luajit tools/frbake.lua <ForeverRecipes folder> [RecipeData.lua]")

local ns = {}
for _, f in ipairs({ "Data/Recipes.lua", "Data/Sources.lua" }) do
    assert(loadfile(src .. "/" .. f))("ForeverRecipes", ns)
end
local version = "?"
for line in io.lines(src .. "/ForeverRecipes.toc") do
    version = line:match("^## Version:%s*(%S+)") or version
end

-- Profession skill lines. Herbalism, Skinning and Fishing only have camping recipes: left out.
local LINES = { [164] = "Blacksmithing", [165] = "Leatherworking", [171] = "Alchemy", [185] = "Cooking",
    [186] = "Mining", [197] = "Tailoring", [202] = "Engineering", [333] = "Enchanting", [129] = "First Aid",
    [40] = "Poisons" }

--- The trainer cost and skill most trainers ask (a few charge more for a higher rank).
local function training(list)
    local counts, best, bestN = {}, nil, 0
    for _, t in ipairs(list or {}) do
        local k = (t[2] or 0) .. ":" .. (t[3] or 0)
        counts[k] = (counts[k] or 0) + 1
        if counts[k] > bestN or (counts[k] == bestN and (t[2] or 0) < best[2]) then best, bestN = t, counts[k] end
    end
    if best then return best[2] or 0, best[3] end
end

local spells = {}
for spell, r in pairs(ns.Recipes) do
    if LINES[r[1]] then spells[#spells + 1] = spell end
end
table.sort(spells)

local function q(s) return string.format("%q", s) end
local lines, counts, differ = {}, {}, 0
for _, spell in ipairs(spells) do
    local r = ns.Recipes[spell]
    local th, product = r[2], r[4]
    local meta = ns.RecipeMeta and ns.RecipeMeta[spell] or {}
    local cost, skill = training(ns.Trainers[spell])
    if not cost and ns.AutomaticRecipes and ns.AutomaticRecipes[spell] then cost, skill = 0, th[1] end
    if skill and skill ~= th[1] then differ = differ + 1 end
    local reagents = {}
    for i = 1, #(r[3] or {}), 2 do reagents[#reagents + 1] = r[3][i] .. "," .. r[3][i + 1] end
    local made = product and product[2] or 1
    made = (made == math.floor(made)) and string.format("%d", made) or tostring(made)
    -- { prof, learn, yellow, green, grey, item, made, recipe item, train cost, specialisation, name, { reagent, count, ... } }
    lines[#lines + 1] = string.format("[%d]={%q,%d,%d,%d,%d,%s,%s,%s,%s,%s,%s,{%s}},", spell, LINES[r[1]],
        th[1], th[2], th[3], th[4], product and product[1] and tostring(product[1]) or "false", made,
        r[5] and tostring(r[5]) or "false", cost and tostring(cost) or "false",
        meta.requiredSpecialization and tostring(meta.requiredSpecialization) or "false",
        q(ns.RecipeNames[spell] or ("spell " .. spell)), table.concat(reagents, ","))
    counts[LINES[r[1]]] = (counts[LINES[r[1]]] or 0) + 1
end

local f = assert(io.open(out, "wb"))
f:write("-- Generated by tools/frbake.lua from ForeverRecipes " .. version .. "; do not edit.\n",
    "-- ForeverRecipes (GPL-3.0) by Ismail and contributors: WoW Forever client exports, author-collected\n",
    "-- observations and CMaNGOS Classic DB reference data (GPL-3.0, https://github.com/cmangos/classic-db).\n",
    "local _, AskBot = ...\n",
    "AskBot.RecipeData = { version = " .. q(version) .. ", crafts = {\n",
    table.concat(lines, "\n"), "\n} }\n")
f:close()

local parts = {}
for prof, n in pairs(counts) do parts[#parts + 1] = prof .. " " .. n end
table.sort(parts)
print(#lines .. " recipes from ForeverRecipes " .. version .. ": " .. table.concat(parts, ", "))
print(differ .. " where the trainer's skill differs from the learn threshold")
